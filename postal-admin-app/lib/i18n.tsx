const MESSAGES: Record<TLocale, Record<string, string>> = { en: EN, ar: AR };

interface II18nContext {
  locale: TLocale;
  isRtl: boolean;
  setLocale: (locale: TLocale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<II18nContext | undefined>(undefined);

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [locale, setLocaleState] = useState<TLocale>('en');

  useEffect(() => {
    void SecureStore.getItemAsync(STORAGE_KEY).then((stored) => {
      if (stored === 'ar' || stored === 'en') setLocaleState(stored);
    });
  }, []);

  const setLocale = useCallback((next: TLocale) => {
    setLocaleState(next);
    void SecureStore.setItemAsync(STORAGE_KEY, next);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let message = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
      if (params) {
        Object.entries(params).forEach(([name, value]) => {
          message = message.replace(new RegExp(`{${name}}`, 'g'), String(value));
        });
      }
      return message;
    },
    [locale],
  );

  const value = useMemo(
    () => ({ locale, isRtl: locale === 'ar', setLocale, t }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): II18nContext => {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
};
